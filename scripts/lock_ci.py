"""Resolve the CI dependency locks (.github/pins/*.lock) for Linux x86-64, Python 3.12.

Run this ONLY to change CI dependency versions on purpose, then open a pull request: CI runs the tests against the new locks.
    pip install uv==0.13.1        # the resolver; any machine works, Windows included
    python scripts/lock_ci.py

uv resolves for the target platform (not the machine you run it on), so Linux-only dependencies are included and Windows-only ones
are not. Each .in file is resolved against two sets of constraints, so nothing floats:
  - backend/constraints.txt, the versions production installs on the VM, and
  - .github/pins/ibm-base-image.txt, the versions IBM's base image ships (used only where a package overlaps, for example numpy,
    scipy, xgboost, httpx).
Nothing is installed.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PINS = ROOT / ".github" / "pins"
TARGETS = ("minimal", "full")


def main() -> None:
    for name in TARGETS:
        out = PINS / f"{name}.lock"
        subprocess.run(
            [
                sys.executable, "-m", "uv", "pip", "compile", str(PINS / f"{name}.in"),
                "--python-version", "3.12", "--python-platform", "x86_64-unknown-linux-gnu",
                "-c", str(ROOT / "backend" / "constraints.txt"), "-c", str(PINS / "ibm-base-image.txt"),
                "--no-header", "--no-annotate", "--quiet", "-o", str(out),
            ],
            check=True,
        )
        header = (
            f"# Generated by scripts/lock_ci.py from {name}.in for Linux x86-64, Python 3.12. Do not edit by hand.\n"
            "# CI installs exactly this with `pip install --no-deps -r`. To change versions on purpose, rerun the script and open a PR.\n"
        )
        lines = [line for line in out.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")]
        out.write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"{name}.lock: {len(lines)} packages")


if __name__ == "__main__":
    main()
