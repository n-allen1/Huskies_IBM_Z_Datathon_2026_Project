"""Resolve the CI dependency locks (.github/pins/*.lock) for Linux x86-64, Python 3.12.

Run this ONLY to change CI dependency versions on purpose, then open a pull request: CI runs the tests against the new locks.
    python scripts/lock_ci.py

Each .in file is resolved with pip's own resolver against two sets of constraints, so nothing floats:
  - backend/constraints.txt, the versions production installs on the VM, and
  - .github/pins/ibm-base-image.txt, the versions IBM's base image ships (used only where a package overlaps, for example numpy,
    scipy, xgboost, httpx).
Nothing is installed; pip only reports what it would install. Needs pip 23.1+ and network access.
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PINS = ROOT / ".github" / "pins"
TARGETS = ("minimal", "full")


def resolve(name: str) -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [
            sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--target", str(Path(tmp) / "t"),
            "--report", str(report), "--only-binary=:all:", "--python-version", "3.12", "--implementation", "cp", "--abi", "cp312",
            "--platform", "manylinux2014_x86_64", "--platform", "manylinux_2_17_x86_64", "--platform", "manylinux_2_28_x86_64",
            "--platform", "manylinux_2_34_x86_64", "--platform", "linux_x86_64",
            "-c", str(ROOT / "backend" / "constraints.txt"), "-c", str(PINS / "ibm-base-image.txt"),
            "-r", str(PINS / f"{name}.in"),
        ]
        subprocess.run(cmd, check=True)
        data = json.loads(report.read_text(encoding="utf-8"))
    pins = {item["metadata"]["name"].lower().replace("_", "-"): item["metadata"]["version"] for item in data["install"]}
    return [f"{k}=={v}" for k, v in sorted(pins.items())]


def main() -> None:
    for name in TARGETS:
        lines = resolve(name)
        header = (
            f"# Generated by scripts/lock_ci.py from {name}.in for Linux x86-64, Python 3.12. Do not edit by hand.\n"
            "# CI installs exactly this with `pip install -r`. To change versions on purpose, rerun the script and open a PR.\n"
        )
        (PINS / f"{name}.lock").write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"{name}.lock: {len(lines)} packages")


if __name__ == "__main__":
    main()
