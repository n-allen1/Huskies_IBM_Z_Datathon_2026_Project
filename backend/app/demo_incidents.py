"""Synthetic demo incidents, seeded when SEED_INCIDENTS=true so a deployed demo never starts with an empty queue.

The incidents live in demo_incidents.json, generated by scripts/seed_incidents.py: real non-residential addresses in
North Topeka, geocoded once ahead of time, so seeding needs no network. They go through the same service calls as
intake (create, then a confirmed category), so their timeline and audit trail read like any other incident.
"""

import json
from pathlib import Path

from .auth import DEMO_USERS
from .models import ClassificationCreate, ClassificationMode, IncidentCategory, IncidentCreate, Location

DATA = Path(__file__).with_name("demo_incidents.json")
_SEEDER = DEMO_USERS["demo-call-taker"]


def load() -> list[tuple[IncidentCreate, IncidentCategory]]:
    records = json.loads(DATA.read_text(encoding="utf-8"))
    return [
        (
            IncidentCreate(
                narrative=r["narrative"], location=Location.model_validate(r["location"]), priority=r.get("priority"),
                reportedCategory=r["category"], isSynthetic=True,
            ),
            IncidentCategory(r["category"]),
        )
        for r in records
    ]


def seed(services) -> int:
    """Create the demo incidents if the store has none (a persistent store keeps its own). Returns how many were created."""
    if services.store.list_incidents():
        return 0
    created = 0
    for body, category in load():
        incident = services.create_incident(_SEEDER, body)
        services.create_classification(
            _SEEDER, incident.incidentId, ClassificationCreate(mode=ClassificationMode.confirm, category=category)
        )
        created += 1
    return created
